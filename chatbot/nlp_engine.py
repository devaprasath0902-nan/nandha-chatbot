"""
NLP Engine for the Nandha Arts and Science College Admission Chatbot.

Approach:
- Intent classification via TF-IDF vectorization + cosine similarity
  over a bank of labeled sample patterns (chatbot/intents.json).
- Lightweight text normalization (lowercase, punctuation strip) acts
  as the NLP preprocessing step.
- Entity extraction: simple keyword/course-name matching against the
  courses table so answers can be personalized (e.g. "fee for BCA").
- Dynamic responses are generated by querying SQLite live, so the
  chatbot never gives stale answers if the admin updates the DB.
"""
import json
import os
import re
import sqlite3
import difflib

from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity

BASE_DIR = os.path.dirname(__file__)
INTENTS_PATH = os.path.join(BASE_DIR, "intents.json")
DB_PATH = os.path.join(BASE_DIR, "..", "database", "admission.db")

CONFIDENCE_THRESHOLD = 0.30  # below this -> fallback intent


def normalize(text: str) -> str:
    text = text.lower().strip()
    text = re.sub(r"[^a-z0-9\s]", " ", text)
    text = re.sub(r"\s+", " ", text)
    return text


class IntentClassifier:
    """TF-IDF + cosine-similarity intent matcher."""

    def __init__(self, intents_path=INTENTS_PATH):
        with open(intents_path, "r") as f:
            self.intents = json.load(f)

        self.pattern_texts = []
        self.pattern_labels = []
        for intent_name, data in self.intents.items():
            for pattern in data["patterns"]:
                self.pattern_texts.append(normalize(pattern))
                self.pattern_labels.append(intent_name)

        # A small custom stopword list (not sklearn's full 'english' list, which
        # strips words like "who"/"you" that carry signal in short queries such
        # as "who are you").
        custom_stopwords = [
            "a", "an", "the", "is", "are", "am", "do", "does", "did", "please",
            "kindly", "could", "would", "will", "to", "of", "for", "in", "on",
            "it", "this", "that", "and", "or", "so", "i", "me", "my",
        ]

        self.vectorizer = TfidfVectorizer(
            ngram_range=(1, 2),          # reward phrase-level overlap, not just stray single words
            stop_words=custom_stopwords,  # trim only truly low-signal filler words
            sublinear_tf=True,
        )
        self.pattern_vectors = self.vectorizer.fit_transform(self.pattern_texts)

    def classify(self, message: str):
        norm_msg = normalize(message)
        if not norm_msg:
            return "fallback", 0.0

        msg_vec = self.vectorizer.transform([norm_msg])
        sims = cosine_similarity(msg_vec, self.pattern_vectors)[0]
        best_idx = sims.argmax()
        best_score = float(sims[best_idx])
        best_label = self.pattern_labels[best_idx]

        if best_score < CONFIDENCE_THRESHOLD:
            return "fallback", best_score

        return best_label, best_score


class ResponseGenerator:
    """Builds the final reply text, pulling live data from SQLite for dynamic intents."""

    def __init__(self, intents_path=INTENTS_PATH, db_path=DB_PATH):
        with open(intents_path, "r") as f:
            self.intents = json.load(f)
        self.db_path = db_path

    def _query(self, sql, params=()):
        conn = sqlite3.connect(self.db_path)
        conn.row_factory = sqlite3.Row
        cur = conn.cursor()
        cur.execute(sql, params)
        rows = cur.fetchall()
        conn.close()
        return rows

    def _extract_course(self, message: str):
        """Try to find a course/branch mentioned in the user's message."""
        rows = self._query("SELECT course_name, course_code FROM courses")
        msg = normalize(message)
        for row in rows:
            code = row["course_code"].lower()
            name_tokens = normalize(row["course_name"])
            if code in msg.split():
                return row["course_name"]
            # fuzzy check against full course name
            if difflib.SequenceMatcher(None, msg, name_tokens).ratio() > 0.35 and any(
                tok in msg for tok in name_tokens.split() if len(tok) > 3
            ):
                return row["course_name"]
        return None

    # ---------- dynamic builders ----------
    def _courses_list(self):
        rows = self._query("SELECT course_name, duration, department FROM courses ORDER BY department")
        lines = ["Here are the courses we currently offer:\n"]
        for r in rows:
            lines.append(f"• {r['course_name']} ({r['duration']}) — {r['department']}")
        lines.append("\nAsk me about eligibility or fees for any specific course!")
        return "\n".join(lines)

    def _eligibility(self, message):
        course = self._extract_course(message)
        if course:
            row = self._query("SELECT eligibility FROM courses WHERE course_name=?", (course,))
            if row:
                return f"Eligibility for {course}: {row[0]['eligibility']}"
        rows = self._query("SELECT course_name, eligibility FROM courses")
        lines = ["Eligibility criteria vary by course:\n"]
        for r in rows:
            lines.append(f"• {r['course_name']}: {r['eligibility']}")
        return "\n".join(lines)

    def _fees(self, message):
        course = self._extract_course(message)
        if course:
            row = self._query("SELECT annual_fee FROM courses WHERE course_name=?", (course,))
            if row:
                fee = row[0]["annual_fee"]
                return f"The annual tuition fee for {course} is ₹{fee:,} per year (excluding hostel and exam fees)."
        rows = self._query("SELECT course_name, annual_fee FROM courses ORDER BY annual_fee")
        lines = ["Here is the annual fee structure by course:\n"]
        for r in rows:
            lines.append(f"• {r['course_name']}: ₹{r['annual_fee']:,} / year")
        return "\n".join(lines)

    def _scholarships(self):
        rows = self._query("SELECT name, eligibility, benefit FROM scholarships")
        lines = ["We offer the following scholarships:\n"]
        for r in rows:
            lines.append(f"• {r['name']} — {r['benefit']} (Eligibility: {r['eligibility']})")
        lines.append("\nScholarship applications open along with the admission form.")
        return "\n".join(lines)

    def _dates(self):
        rows = self._query("SELECT event, event_date FROM important_dates")
        lines = ["Important admission dates:\n"]
        for r in rows:
            lines.append(f"• {r['event']}: {r['event_date']}")
        return "\n".join(lines)

    def _documents(self):
        rows = self._query("SELECT document_name FROM documents")
        lines = ["Please keep the following documents ready:\n"]
        for r in rows:
            lines.append(f"• {r['document_name']}")
        return "\n".join(lines)

    def _faq(self, keyword_like):
        rows = self._query("SELECT answer FROM faqs WHERE question LIKE ?", (f"%{keyword_like}%",))
        if rows:
            return rows[0]["answer"]
        return None

    # ---------- main entry ----------
    def generate(self, intent: str, message: str) -> str:
        dynamic_map = {
            "courses_offered": lambda: self._courses_list(),
            "eligibility_criteria": lambda: self._eligibility(message),
            "fee_structure": lambda: self._fees(message),
            "scholarship": lambda: self._scholarships(),
            "important_dates": lambda: self._dates(),
            "required_documents": lambda: self._documents(),
            "hostel_facility": lambda: self._faq("hostel") or "Hostel details are currently unavailable.",
            "placement_info": lambda: self._faq("placement") or "Placement details are currently unavailable.",
            "management_quota": lambda: self._faq("management quota") or "Please contact the admission office for quota details.",
            "multiple_applications": lambda: self._faq("more than one course") or "Please contact the admission office for this query.",
            "entrance_exam": lambda: self._faq("entrance exam") or "Please contact the admission office for exam-related queries.",
            "contact_info": lambda: self._faq("contact the admission office") or "Email: info@nandhaarts.org | Phone: 04294-222788 / +91 73737 24422",
        }

        if intent in dynamic_map:
            return dynamic_map[intent]()

        if intent in self.intents:
            responses = self.intents[intent]["responses"]
            return responses[0]

        return ("I'm sorry, I couldn't quite understand that. You can ask me about courses, "
                "eligibility, fees, scholarships, hostel facilities, placements, required documents, "
                "or important admission dates. You can also reach the admission office directly at "
                "info@nandhaarts.org.")


class ChatBot:
    def __init__(self):
        self.classifier = IntentClassifier()
        self.responder = ResponseGenerator()

    def get_response(self, message: str):
        intent, confidence = self.classifier.classify(message)
        reply = self.responder.generate(intent, message)
        return {
            "intent": intent,
            "confidence": round(confidence, 3),
            "response": reply,
        }
